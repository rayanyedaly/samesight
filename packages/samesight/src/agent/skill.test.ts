import { readdirSync, readFileSync } from "node:fs";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { parse } from "yaml";
import { RULE_NAMES } from "../lint/lint.ts";
import { SKILL_DIR as SHIPPED, skillFiles } from "./skill.ts";

const SKILL_DIR = fileURLToPath(new URL("../../skills/samesight/", import.meta.url));
const REFERENCES = join(SKILL_DIR, "references");

const skill = readFileSync(join(SKILL_DIR, "SKILL.md"), "utf8");
const references = readdirSync(REFERENCES)
  .filter((f) => f.endsWith(".md"))
  .sort();
const readReference = (file: string) => readFileSync(join(REFERENCES, file), "utf8");

/** Every Markdown link target in a text, outside fenced code. */
function linkTargets(text: string): string[] {
  const prose = text.replace(/^```[\s\S]*?^```$/gm, "");
  return [...prose.matchAll(/\]\(([^)\s]+)\)/g)].map((m) => m[1] as string);
}

describe("the samesight skill", () => {
  it("is where agent init and the hook look for it, with every file", () => {
    expect(skillFiles(SHIPPED)).toEqual(["SKILL.md", ...references.map((f) => `references/${f}`)]);
  });

  const frontmatter = /^---\n([\s\S]*?)\n---\n/.exec(skill);

  it("has frontmatter with only a name, a description and a license", () => {
    expect(frontmatter).not.toBeNull();
    const data = parse(frontmatter?.[1] ?? "") as Record<string, unknown>;
    expect(Object.keys(data).sort()).toEqual(["description", "license", "name"]);
    expect(data.license).toBe("MIT");
  });

  it("is named after its directory, in lowercase words joined by hyphens", () => {
    const { name } = parse(frontmatter?.[1] ?? "") as { name: string };
    expect(name).toBe(basename(SKILL_DIR));
    expect(name).toBe("samesight");
    expect(name).toMatch(/^[a-z0-9]+(-[a-z0-9]+)*$/);
  });

  it("has a description of at most 1024 characters", () => {
    const { description } = parse(frontmatter?.[1] ?? "") as { description: string };
    expect(typeof description).toBe("string");
    expect(description.length).toBeGreaterThan(0);
    expect(description.length).toBeLessThanOrEqual(1024);
  });

  it("keeps SKILL.md under 500 lines", () => {
    expect(skill.split("\n").length).toBeLessThan(500);
  });

  it("has one reference per lint rule, and no reference for a rule that does not exist", () => {
    const rules = references.filter((f) => f !== "json.md").map((f) => f.slice(0, -".md".length));
    expect(rules.sort()).toEqual([...RULE_NAMES].sort());
    for (const id of RULE_NAMES) {
      const text = readReference(`${id}.md`);
      expect(text.split("\n")[0], id).toBe(`<!-- generated by scripts/docs/skill.mjs from docs/rules/${id}.md; do not edit -->`);
      expect(text, id).toContain(`\n# ${id}\n`);
    }
  });

  it("links each rule's reference, and the JSON reference, from SKILL.md", () => {
    const targets = linkTargets(skill);
    for (const id of RULE_NAMES) expect(targets, id).toContain(`references/${id}.md`);
    expect(targets).toContain("references/json.md");
  });

  it("links from SKILL.md only to its references or to absolute URLs", () => {
    for (const target of linkTargets(skill)) {
      if (target.startsWith("https://")) continue;
      expect(target).toMatch(/^references\/[a-z0-9-]+\.md$/);
      expect(references, target).toContain(target.slice("references/".length));
    }
  });

  it("links from the references only to absolute URLs or anchors", () => {
    for (const file of references) {
      for (const target of linkTargets(readReference(file))) {
        expect(target, `${file}: ${target}`).toMatch(/^(https:\/\/|#)/);
      }
    }
  });

  it("uses no em dash in any file", () => {
    for (const [file, text] of [["SKILL.md", skill], ...references.map((f) => [`references/${f}`, readReference(f)])]) {
      expect(text.includes("\u2014"), file).toBe(false);
    }
  });
});

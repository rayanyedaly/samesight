/**
 * Files the app and the PowerSync service read: the client SQLite schema, the policy's
 * roles and claims as TypeScript, the local service config, and a manifest the verifier
 * reads.
 */

import { createHash } from "node:crypto";
import type { IR, IRTable } from "../ir.ts";
import type { ColumnInfo } from "../schema.ts";

/** PowerSync stores text, integer and real; booleans sync as 0/1. */
function columnType(c: ColumnInfo): "text" | "integer" | "real" {
  if (/^(smallint|integer|bigint|boolean)$/.test(c.type)) return "integer";
  if (/^(real|double precision)$/.test(c.type)) return "real";
  return "text"; // numeric stays text to keep its precision
}

export function emitClientSchema(ir: IR, options: { import?: string } = {}): string {
  const from = options.import ?? "@powersync/web";
  const synced = ir.tables.filter((t) => t.read.size > 0);
  const out = [
    `import { column, Schema, Table } from ${JSON.stringify(from)};`,
    `import { rejectedWriteTable } from "@samesight/supabase";`,
    "",
    "// Generated by samesight from samesight.policy.ts. Do not edit: change the policy and run",
    "// `samesight generate`. One table per synced Postgres table, as the sync streams send it.",
  ];
  for (const t of synced) {
    out.push("", `const ${t.name} = new Table({`);
    for (const c of t.columns) {
      if (c.name === "id") continue;
      const note = columnNote(t, c, ir.claims.roles);
      if (note) out.push(`  // ${note}`);
      out.push(`  ${propertyKey(c.name)}: column.${columnType(c)},`);
    }
    out.push("});");
  }
  out.push(
    "",
    "// RejectedWrite is local-only: writes the server refused for good, kept and shown.",
    "export const AppSchema = new Schema({",
    ...synced.map((t) => `  ${t.name},`),
    "  RejectedWrite: rejectedWriteTable,",
    "});",
    "",
    `export type Database = (typeof AppSchema)["types"];`,
    ...synced.map((t) => `export type ${t.name}Record = Database[${JSON.stringify(t.name)}];`),
  );
  return `${out.join("\n")}\n`;
}

function columnNote(t: IRTable, c: ColumnInfo, roles: string[]): string | undefined {
  const hiddenFrom = roles.filter((r) => t.read.has(r) && t.hide.get(r)?.includes(c.name));
  if (hiddenFrom.length) return `Not synced to ${hiddenFrom.join(", ")}; always null on their devices.`;
  if (c.identity || c.name === t.appendOnly?.order) return "Assigned by the server; null until the row has synced.";
  return undefined;
}

function propertyKey(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

export function emitPolicyTypes(ir: IR): string {
  const roles = ir.claims.roles.map((r) => JSON.stringify(r)).join(", ");
  return [
    "// Generated by samesight from samesight.policy.ts. Do not edit.",
    "",
    "/** The token claims the access token hook adds. */",
    `export const CLAIMS = { tenant: ${JSON.stringify(ir.claims.tenant)}, role: ${JSON.stringify(ir.claims.role)} } as const;`,
    "",
    `export const ROLES = [${roles}] as const;`,
    "export type AppRole = (typeof ROLES)[number];",
    "",
    "export function isAppRole(value: unknown): value is AppRole {",
    "  return (ROLES as readonly unknown[]).includes(value);",
    "}",
    "",
    "/** Tables a client writes through apply_batch, and the columns it may set. */",
    "export const WRITABLE = {",
    ...ir.tables
      .filter((t) => t.insert.size + t.update.size + t.delete.size > 0)
      .map(
        (t) =>
          `  ${propertyKey(t.name)}: { insert: [${t.insertColumns.map((c) => JSON.stringify(c)).join(", ")}], update: [${t.updateColumns.map((c) => JSON.stringify(c)).join(", ")}], appendOnly: ${Boolean(t.appendOnly)} },`,
      ),
    "} as const;",
    "",
  ].join("\n");
}

export function emitServiceConfig(options: { syncConfigPath: string; jwksUri: string }): string {
  return [
    "# yaml-language-server: $schema=https://unpkg.com/@powersync/service-schema@latest/json-schema/powersync-config.json",
    "#",
    "# Generated by samesight. Local development only: PowerSync Cloud and production",
    "# deployments use their own settings. Holds no secrets: the connection strings come from",
    "# the environment (PS_DATA_SOURCE_URI, PS_STORAGE_URI).",
    "",
    "telemetry:",
    "  disable_telemetry_sharing: true",
    "",
    "replication:",
    "  connections:",
    "    - type: postgresql",
    "      uri: !env PS_DATA_SOURCE_URI",
    "      sslmode: disable",
    "",
    "storage:",
    "  type: postgresql",
    "  uri: !env PS_STORAGE_URI",
    "  sslmode: disable",
    "",
    "port: 8080",
    "",
    "sync_config:",
    `  path: ${options.syncConfigPath}`,
    "",
    "client_auth:",
    "  # Verify Supabase Auth tokens against the local project's JWKS.",
    "  supabase: true",
    `  jwks_uri: ${options.jwksUri}`,
    `  audience: ["authenticated"]`,
    "",
  ].join("\n");
}

/** What the verifier needs to know about the policy, plus hashes tying it to the output. */
export function emitManifest(ir: IR, outputs: Record<string, string>): string {
  const rule = (r: unknown) => (r === true ? "all" : r);
  const manifest = {
    generator: "samesight",
    claims: ir.claims,
    membership: ir.membership,
    tenantTable: ir.tenantTable ?? null,
    tables: ir.tables.map((t) => ({
      name: t.name,
      tenant: t.tenant,
      read: Object.fromEntries([...t.read].map(([role, r]) => [role, rule(r)])),
      insert: Object.fromEntries([...t.insert].map(([role, r]) => [role, rule(r)])),
      update: Object.fromEntries([...t.update].map(([role, r]) => [role, rule(r)])),
      delete: Object.fromEntries([...t.delete].map(([role, r]) => [role, rule(r)])),
      check: t.check ?? null,
      hide: Object.fromEntries(t.hide),
      insertColumns: t.insertColumns,
      updateColumns: t.updateColumns,
      appendOnly: t.appendOnly ?? null,
    })),
    outputs: Object.fromEntries(
      Object.entries(outputs).map(([path, text]) => [path, createHash("sha256").update(text).digest("hex")]),
    ),
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

/**
 * The PowerSync sync config (Edition 3 streams). PowerSync replicates through a BYPASSRLS
 * role, so these streams are the only filter between the database and a device; each
 * query is the read rule its RLS policy enforces, said in stream SQL:
 *   - one auto-subscribed stream per role, every query gated on the role claim;
 *   - the tenant gate on every query and CTE;
 *   - a via rule (a child is visible when its parent is) as a CTE of the parent's rows
 *     under the same role's rule, plus IN; a rowsOf rule the same way, over the rows of
 *     its table this role reads that match its where;
 *   - value lists as OR chains;
 *   - columns hidden from a role left out of its projection.
 */

import { type IR, type IRTable, snake } from "../ir.ts";
import type { ConditionNode } from "../policy.ts";
import { ident, literal, sync } from "./expr.ts";

type Sub = Extract<ConditionNode, { kind: "via" | "inRows" }>;

export function emitSyncConfig(ir: IR): string {
  const out: string[] = [
    "# yaml-language-server: $schema=https://unpkg.com/@powersync/service-sync-rules@latest/schema/sync_rules.json",
    "#",
    "# Generated by samesight from samesight.policy.ts. Do not edit: change the policy and run",
    "# `samesight generate`. The service reads this file at startup; restart it after a change.",
    "",
    "config:",
    "  edition: 3",
    "",
    "streams:",
  ];
  // A shared table (tenant: null) has no tenant gate: every tenant receives the same rows.
  const tenantGate = (t: IRTable) => (t.tenant === null ? [] : [`${ident(t.tenant)} = auth.parameter(${literal(ir.claims.tenant)})`]);
  const byName = new Map(ir.tables.map((t) => [t.name, t]));

  for (const role of ir.claims.roles) {
    const tables = ir.tables.filter((t) => t.read.has(role));
    if (tables.length === 0) continue;
    const roleGate = `auth.parameter(${literal(ir.claims.role)}) = ${literal(role)}`;

    // One CTE per subquery: (parent, key) for a via, (table, column, where) for a rowsOf.
    // The rows this role reads of that table. Keyed by the subquery, never by the name, so
    // two subqueries can never share a CTE; names that collide with each other or with a
    // table get a numeric suffix.
    const ctes = new Map<string, { name: string; sql: string }>();
    const taken = new Set(ir.tables.map((t) => t.name.toLowerCase()));
    const cteName = (n: Sub) => {
      const target = n.kind === "via" ? n.parent : n.rows.table;
      const column = n.kind === "via" ? n.parentKey : n.rows.column;
      const key = JSON.stringify(n.kind === "via" ? ["via", target, column] : ["rows", target, column, n.rows.where ?? null]);
      const existing = ctes.get(key);
      if (existing) return existing.name;
      const table = byName.get(target);
      if (!table) throw new Error(`${target} is not in the policy`);
      const rule = table.read.get(role);
      if (rule === undefined) throw new Error(`${role} cannot read ${target}`);
      const base =
        n.kind === "via"
          ? `${snake(target)}_${column === "id" ? "" : `${snake(column)}_`}visible`
          : `${snake(target)}_${snake(column)}_rows`;
      let name = base;
      for (let i = 2; taken.has(name); i++) name = `${base}_${i}`;
      taken.add(name);
      const where = [
        ...tenantGate(table),
        // NULL never matches on the RLS side; say so rather than rely on how streams treat it.
        ...(column === "id" || table.columns.find((c) => c.name === column)?.nullable === false ? [] : [`${ident(column)} IS NOT NULL`]),
        ...(rule === true ? [] : [wrap(rule, sync(rule, noSub))]),
        ...(n.kind === "inRows" && n.rows.where ? [wrap(n.rows.where, sync(n.rows.where, noSub))] : []),
      ];
      // A where that repeats the table's own rule (rowsOf(..., col("userId").eq(claim.user))) says it once.
      ctes.set(key, { name, sql: `SELECT ${ident(column)} FROM ${ident(table.name)}\n        WHERE ${[...new Set(where)].join(" AND ")}` });
      return name;
    };

    const queries = tables.map((t) => {
      const rule = linkedAway(t, t.read.get(role) as true | ConditionNode, role, byName);
      const where = [...tenantGate(t), ...(rule === true ? [] : [wrap(rule, sync(rule, cteName))]), roleGate];
      const hidden = new Set(t.hide.get(role) ?? []);
      const projection = hidden.size === 0 ? "*" : t.columns.filter((c) => !hidden.has(c.name)).map((c) => ident(c.name)).join(", ");
      const sql = `SELECT ${projection} FROM ${ident(t.name)} WHERE ${where.join(" AND ")}`;
      const note = hidden.size ? `      # Every ${t.name} column except ${[...hidden].map((c) => JSON.stringify(c)).join(", ")}.\n` : "";
      // One line when short and YAML-plain-safe (no ": " or " #"); a block scalar otherwise.
      // (Raw SQL is collapsed to one line by the renderer, so no fragment carries a newline.)
      return sql.length > 120 || /: | #/.test(sql)
        ? `${note}      - |\n        SELECT ${projection}\n        FROM ${ident(t.name)}\n        WHERE ${where.join("\n          AND ")}`
        : `${note}      - ${sql}`;
    });

    if (out[out.length - 1] !== "streams:") out.push("");
    out.push(`  ${snake(role)}:`, "    auto_subscribe: true");
    if (ctes.size) {
      out.push("    with:");
      for (const { name, sql } of ctes.values()) out.push(`      ${name}: |`, `        ${sql}`);
    }
    out.push("    queries:", ...queries);
  }
  return `${out.join("\n")}\n`;
}

/**
 * Drops a via the tenant gate already implies: the column is tenant-linked to the parent
 * by a composite foreign key, and the role reads every parent row in its tenant. Saves a
 * CTE, and a bucket per parent row, without widening the stream.
 */
function linkedAway(t: IRTable, rule: true | ConditionNode, role: string, byName: Map<string, IRTable>): true | ConditionNode {
  const implied = (n: ConditionNode) =>
    n.kind === "via" &&
    byName.get(n.parent)?.read.get(role) === true &&
    t.tenantLinked.some((l) => l.column === n.column && l.parent === n.parent && l.key === n.parentKey);
  if (rule === true || implied(rule)) return true;
  if (rule.kind !== "and") return rule;
  const items = rule.items.filter((i) => !implied(i));
  return items.length === 0 ? true : items.length === 1 ? items[0] : { kind: "and", items };
}

const noSub = (n: Sub): string => {
  // Refused by the compiler: a table reached through via or rowsOf has no subquery of its own.
  throw new Error(`nested ${n.kind === "via" ? "via" : "rowsOf"} on ${n.column}`);
};

function wrap(node: ConditionNode, text: string): string {
  return node.kind === "or" ? `(${text})` : text;
}


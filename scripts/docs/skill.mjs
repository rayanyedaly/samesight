#!/usr/bin/env node
/**
 * Keeps the samesight skill (packages/samesight/skills/samesight) true to the rule pages.
 *
 * For each rule in samesight's RULE_INFO it writes references/<id>.md: the rule's level (the
 * Level line of docs/rules/<id>.md), its summary and description from RULE_INFO, then the
 * page's Example, What lint prints, The fix and Accepting it sections (and Marking columns,
 * where the page has it), copied as they are, and a link to the full page. Marker comment
 * lines are dropped, and relative links become links to the docs site (a page) or to the
 * file on GitHub (anything else), as the site's own build maps them.
 *
 * In SKILL.md it rewrites the rules table between these lines:
 *
 *   <!-- rules -->
 *   <!-- /rules -->
 *
 *   node scripts/docs/skill.mjs           write the references and the table
 *   node scripts/docs/skill.mjs --check   exit 1 if any of them differs from a fresh run
 *
 * It reads the sources only (RULE_INFO from its TypeScript file), so it needs no build.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = fileURLToPath(new URL("../..", import.meta.url));
const RULES = "docs/rules";
const SKILL_DIR = "packages/samesight/skills/samesight";
const SKILL = `${SKILL_DIR}/SKILL.md`;
const REFERENCES = `${SKILL_DIR}/references`;
const SITE = "https://rayanyedaly.github.io/samesight/";
const REPO = "https://github.com/rayanyedaly/samesight";
const DOCS_DIR = join(ROOT, "docs");

/** The page sections each reference copies, in this order; the optional ones only where they exist. */
const SECTIONS = ["Example", "What lint prints", "The fix", "Accepting it"];
const OPTIONAL_SECTIONS = ["Marking columns"];

const args = process.argv.slice(2);
const check = args.includes("--check");
if (args.some((a) => a !== "--check")) {
  console.error("Usage: node scripts/docs/skill.mjs [--check]");
  process.exit(2);
}

function fail(message) {
  console.error(`skill.mjs: ${message}`);
  process.exit(2);
}

const { RULE_INFO } = await import(pathToFileURL(join(ROOT, "packages/samesight/src/lint/rule-info.ts")).href);
const ids = Object.keys(RULE_INFO);

const generatedLine = (id) => `<!-- generated by scripts/docs/skill.mjs from ${RULES}/${id}.md; do not edit -->`;

function lines(text) {
  return text.replace(/\r\n/g, "\n").replace(/\n+$/, "").split("\n");
}

const isFence = (line) => /^\s*(```|~~~)/.test(line);

const isInside = (dir, path) => {
  const rel = relative(dir, path);
  return rel === "" || (!rel.startsWith("..") && !isAbsolute(rel));
};

/**
 * Where a link on a rule page points, as an absolute URL: a page of the docs (cli.md#lint,
 * ../exposure.md, index.md) on the site, with its clean URL; any other file of the repository
 * on GitHub; an anchor on the page itself on the rule's page, since the reference does not
 * hold every section.
 */
function absoluteHref(href, page, id) {
  if (/^[a-z][a-z\d+.-]*:/i.test(href)) return href;
  if (href.startsWith("#")) return `${RULE_INFO[id].help}${href}`;
  if (href.startsWith("/")) fail(`${relative(ROOT, page)}: the link ${href} is site-absolute; use a relative link`);
  const cut = href.search(/[?#]/);
  const path = cut < 0 ? href : href.slice(0, cut);
  const rest = cut < 0 ? "" : href.slice(cut);
  const target = resolve(dirname(page), decodeURIComponent(path));
  const where = `${relative(ROOT, page)}: the link ${href}`;
  if (!isInside(ROOT, target)) fail(`${where} points outside the repository`);
  if (!existsSync(target)) fail(`${where} points at ${relative(ROOT, target)}, which does not exist`);
  const isDir = statSync(target).isDirectory();
  if (isInside(DOCS_DIR, target)) {
    const rel = relative(DOCS_DIR, target).split(sep).join("/");
    if (isDir && existsSync(join(target, "index.md"))) return `${SITE}${encodeURI(rel ? `${rel}/` : "")}${rest}`;
    if (!isDir && rel.endsWith(".md")) {
      const clean = rel === "index.md" ? "" : rel.endsWith("/index.md") ? rel.slice(0, -"index.md".length) : rel.slice(0, -".md".length);
      return `${SITE}${encodeURI(clean)}${rest}`;
    }
  }
  return `${REPO}/${isDir ? "tree" : "blob"}/main/${encodeURI(relative(ROOT, target).split(sep).join("/"))}${rest}`;
}

/** A rule page's Level line and its sections by heading, each as lines, fences respected. */
function readPage(id) {
  const page = join(ROOT, RULES, `${id}.md`);
  if (!existsSync(page)) fail(`${RULES}/${id}.md is missing; every rule in RULE_INFO needs a page`);
  const all = lines(readFileSync(page, "utf8"));
  const levelLine = all.find((l) => l.startsWith("Level: "));
  if (!levelLine) fail(`${RULES}/${id}.md has no "Level: " line`);
  const sections = new Map();
  let current;
  let fenced = false;
  for (const line of all) {
    if (!fenced && line.startsWith("## ")) {
      const heading = line.slice(3).trim();
      if (sections.has(heading)) fail(`${RULES}/${id}.md has two "## ${heading}" sections`);
      current = [];
      sections.set(heading, current);
      continue;
    }
    if (isFence(line)) fenced = !fenced;
    current?.push(line);
  }
  return { page, level: levelLine.slice("Level: ".length).trim(), sections };
}

/**
 * A section's lines as the reference holds them: marker comment lines dropped, relative
 * links made absolute, runs of blank lines folded, all outside fenced code only.
 */
function copySection(body, page, id) {
  const out = [];
  let fenced = false;
  for (const line of body) {
    if (isFence(line)) {
      fenced = !fenced;
      out.push(line);
      continue;
    }
    if (fenced) {
      out.push(line);
      continue;
    }
    if (/^\s*<!--.*-->\s*$/.test(line)) continue;
    if (line.trim() === "" && (out.length === 0 || out[out.length - 1].trim() === "")) continue;
    out.push(line.replace(/\]\(([^)\s]+)\)/g, (_, href) => `](${absoluteHref(href, page, id)})`));
  }
  if (fenced) fail(`${relative(ROOT, page)} has a code fence that is never closed`);
  while (out.length && out[out.length - 1].trim() === "") out.pop();
  return out;
}

function reference(id) {
  const info = RULE_INFO[id];
  const { page, level, sections } = readPage(id);
  if (!level.startsWith(info.level)) fail(`${RULES}/${id}.md says "Level: ${level}", but RULE_INFO gives ${id} the level ${info.level}`);
  const out = [generatedLine(id), `# ${id}`, "", `Level: ${level}`, "", info.summary, "", info.description];
  for (const heading of [...SECTIONS, ...OPTIONAL_SECTIONS]) {
    const body = sections.get(heading);
    if (!body) {
      if (SECTIONS.includes(heading)) fail(`${RULES}/${id}.md has no "## ${heading}" section`);
      continue;
    }
    out.push("", `## ${heading}`, "", ...copySection(body, page, id));
  }
  out.push("", `The full page, with what the rule catches and what audit does with it: ${info.help}`);
  return { level, text: `${out.join("\n")}\n` };
}

/** The rule's level as the table shows it: "error, or warning" from the page's longer line. */
function shortLevel(id, level) {
  const m = /^([a-z]+(?:, or [a-z]+)?)/.exec(level);
  if (!m) fail(`${RULES}/${id}.md has a Level line that does not start with a level: ${level}`);
  return m[1];
}

const cell = (text) => text.replace(/\|/g, "\\|");

const expected = new Map();
const rows = ["| Rule | Level | What it catches | How to fix |", "| --- | --- | --- | --- |"];
for (const id of ids) {
  const { level, text } = reference(id);
  if (text.includes("\u2014")) fail(`${RULES}/${id}.md holds an em dash, which the skill does not use; write it another way`);
  expected.set(`${REFERENCES}/${id}.md`, text);
  rows.push(`| \`${id}\` | ${shortLevel(id, level)} | ${cell(RULE_INFO[id].summary)} | [references/${id}.md](references/${id}.md) |`);
}

// The rules table in SKILL.md.
const skillBefore = readFileSync(join(ROOT, SKILL), "utf8");
const blocks = skillBefore.match(/^<!-- rules -->\n[\s\S]*?^<!-- \/rules -->$/gm) ?? [];
if (blocks.length !== 1) fail(`${SKILL} needs one rules block: <!-- rules --> and <!-- /rules --> on lines of their own`);
const skillAfter = skillBefore.replace(/^<!-- rules -->\n[\s\S]*?^<!-- \/rules -->$/m, () => ["<!-- rules -->", ...rows, "<!-- /rules -->"].join("\n"));
expected.set(SKILL, skillAfter);

// References no rule has: a generated one is stale (a rule that is gone), anything else is
// not this script's to judge, except that it must not look like a rule's.
const strays = [];
const referenceFiles = existsSync(join(ROOT, REFERENCES)) ? readdirSync(join(ROOT, REFERENCES)) : [];
for (const file of referenceFiles.filter((f) => f.endsWith(".md"))) {
  const path = `${REFERENCES}/${file}`;
  if (expected.has(path)) continue;
  const first = readFileSync(join(ROOT, path), "utf8").split("\n", 1)[0];
  if (first.startsWith("<!-- generated by scripts/docs/skill.mjs")) strays.push(path);
}

const stale = [...expected].filter(([path, text]) => !existsSync(join(ROOT, path)) || readFileSync(join(ROOT, path), "utf8") !== text).map(([path]) => path);

if (check) {
  if (stale.length || strays.length) {
    for (const path of stale) console.error(`${path} is stale: it is not what ${path === SKILL ? "RULE_INFO and the rule pages give" : "its rule page and RULE_INFO give"} now`);
    for (const path of strays) console.error(`${path} is stale: no rule in RULE_INFO is named after it`);
    console.error("Run: node scripts/docs/skill.mjs");
    process.exit(1);
  }
  console.log(`${SKILL_DIR}: the rules table and every reference are up to date (${ids.length} rules)`);
} else {
  mkdirSync(join(ROOT, REFERENCES), { recursive: true });
  for (const path of stale) {
    writeFileSync(join(ROOT, path), expected.get(path));
    console.log(`${path}: written`);
  }
  for (const path of strays) {
    rmSync(join(ROOT, path));
    console.log(`${path}: removed, no rule is named after it`);
  }
  if (!stale.length && !strays.length) console.log(`${SKILL_DIR}: up to date`);
}
